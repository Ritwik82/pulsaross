/** Days elapsed since an ISO timestamp. Returns null for missing/invalid input. */
export function daysSince(iso: string | null): number | null {
  if (!iso) return null;
  const t = new Date(iso).getTime();
  if (Number.isNaN(t)) return null;
  return Math.max(0, Math.floor((Date.now() - t) / 86400000));
}

/** CSS colour variable for a 0–1 score. */
export function scoreColor(score: number): string {
  const s = score * 10;
  if (s >= 7) return "var(--color-signal-green)";
  if (s >= 4) return "var(--color-signal-amber)";
  return "var(--color-signal-red)";
}

